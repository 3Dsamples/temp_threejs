/**
 * Extracts the six frustum planes from a view-projection matrix.
 * Planes are stored as (nx, ny, nz, d) in a Float32Array of length 24.
 * Callers pass the output buffer to avoid allocations.
 */
export function extractFrustumPlanes(viewProjection, outPlanes) {
  // Row-major 4x4 matrix. The planes are the four Gribb-Hartmann combinations.
  const m = viewProjection;
  const p = outPlanes;

  // Row 4 (last row) for the standard row-major view-projection matrix.
  const r0x = m[0],  r0y = m[1],  r0z = m[2],  r0w = m[3];
  const r1x = m[4],  r1y = m[5],  r1z = m[6],  r1w = m[7];
  const r2x = m[8],  r2y = m[9],  r2z = m[10], r2w = m[11];
  const r3x = m[12], r3y = m[13], r3z = m[14], r3w = m[15];

  // Left:   r3 + r0
  p[0]  = r3x + r0x; p[1]  = r3y + r0y; p[2]  = r3z + r0z; p[3]  = r3w + r0w;
  // Right:  r3 - r0
  p[4]  = r3x - r0x; p[5]  = r3y - r0y; p[6]  = r3z - r0z; p[7]  = r3w - r0w;
  // Bottom: r3 + r1
  p[8]  = r3x + r1x; p[9]  = r3y + r1y; p[10] = r3z + r1z; p[11] = r3w + r1w;
  // Top:    r3 - r1
  p[12] = r3x - r1x; p[13] = r3y - r1y; p[14] = r3z - r1z; p[15] = r3w - r1w;
  // Near:   r3 + r2
  p[16] = r3x + r2x; p[17] = r3y + r2y; p[18] = r3z + r2z; p[19] = r3w + r2w;
  // Far:    r3 - r2
  p[20] = r3x - r2x; p[21] = r3y - r2y; p[22] = r3z - r2z; p[23] = r3w - r2w;

  // Normalize each plane (so the dot product is a signed distance).
  for (let i = 0; i < 24; i += 4) {
    const nx = p[i], ny = p[i + 1], nz = p[i + 2], d = p[i + 3];
    const len = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;
    p[i]     = nx / len;
    p[i + 1] = ny / len;
    p[i + 2] = nz / len;
    p[i + 3] = d / len;
  }
}

/**
 * Tests whether a bounding sphere is outside any frustum plane.
 * Returns true if the sphere is culled (outside).
 * `planes` must be the 24-float output of extractFrustumPlanes.
 */
export function isSphereOutsideFrustum(planes, cx, cy, cz, radius) {
  for (let i = 0; i < 24; i += 4) {
    const nx = planes[i];
    const ny = planes[i + 1];
    const nz = planes[i + 2];
    const d  = planes[i + 3];
    if (nx * cx + ny * cy + nz * cz + d < -radius) {
      return true; // fully outside
    }
  }
  return false;
}

/**
 * Tests whether an axis-aligned box is outside any frustum plane.
 * Returns true if the box is culled.
 * `planes` must be the 24-float output of extractFrustumPlanes.
 */
export function isBoxOutsideFrustum(planes, minX, minY, minZ, maxX, maxY, maxZ) {
  for (let i = 0; i < 24; i += 4) {
    const nx = planes[i];
    const ny = planes[i + 1];
    const nz = planes[i + 2];
    const d  = planes[i + 3];
    // Positive vertex: the corner with the most positive projection on (nx, ny, nz).
    const px = nx >= 0 ? maxX : minX;
    const py = ny >= 0 ? maxY : minY;
    const pz = nz >= 0 ? maxZ : minZ;
    if (nx * px + ny * py + nz * pz + d < 0) {
      return true; // fully outside
    }
  }
  return false;
}

/**
 * Computes the squared distance from a camera position to a bounding sphere.
 * Squared distance avoids the square root when only ordering is needed
 * (blueprint step 3: spatial distances stored squared until screen coverage
 * needs the square root).
 */
export function distanceToSphereSquared(camX, camY, camZ, cx, cy, cz, radius) {
  const dx = cx - camX;
  const dy = cy - camY;
  const dz = cz - camZ;
  const distSq = dx * dx + dy * dy + dz * dz;
  const inner = Math.sqrt(distSq) - radius;
  return inner <= 0 ? 0 : inner * inner;
}

/**
 * Computes the screen-space error (in pixels) for a tile.
 * Standard 3D Tiles SSE formula:
 *   SSE = (geometricError / distance) * (screenHeight / (2 * tan(fov/2)))
 * Returns a large value if the camera is closer than the tile radius,
 * so near tiles are always selected.
 */
export function computeScreenSpaceError(geometricError, distance, screenHeight, fovRadians) {
  if (distance <= 0) return Number.MAX_VALUE;
  const factor = screenHeight / (2 * Math.tan(fovRadians * 0.5));
  return (geometricError / distance) * factor;
}

