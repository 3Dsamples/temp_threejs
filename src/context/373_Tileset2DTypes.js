export const SeamEdge = Object.freeze({
  NORTH: 0x01,
  EAST:  0x02,
  SOUTH: 0x04,
  WEST:  0x08
});

/**
 * Returns true if the tile has a seam stitch on the given edge.
 */
export function hasSeam(seamFlags, edgeMask) {
  return (seamFlags & edgeMask) !== 0;
}

/**
 * Returns the canonical opposite edge for a given edge.
 */
export function oppositeEdge(edgeMask) {
  switch (edgeMask) {
    case SeamEdge.NORTH: return SeamEdge.SOUTH;
    case SeamEdge.SOUTH: return SeamEdge.NORTH;
    case SeamEdge.EAST:  return SeamEdge.WEST;
    case SeamEdge.WEST:  return SeamEdge.EAST;
    default: return 0;
  }
}

