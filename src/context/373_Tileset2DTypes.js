/**
 * Computes the log-scale LOD index for a distance.
 *   lod = floor(log_R(d / d0))
 *   threshold = d0 * R^lod
 * Matches blueprint step 19.
 *
 * @param {number} distance – distance from camera to tile center, world units
 * @param {number} d0 – base distance (distance of LOD 0)
 * @param {number} R – ratio between LOD levels (typically 2)
 * @param {number} maxLod – clamp to this value
 * @returns {number} integer LOD index in [0, maxLod]
 */
export function computeLodIndex(distance, d0, R, maxLod) {
  if (distance <= d0 || R <= 1 || !isFinite(R)) return 0;
  const lod = Math.floor(Math.log(distance / d0) / Math.log(R));
  if (lod < 0) return 0;
  if (lod > maxLod) return maxLod;
  return lod;
}

/**
 * Computes the smooth blend weight between two adjacent LOD levels.
 *   alpha = smoothstep(d_lod, d_{lod+1}, d)
 * Returns 0 when the camera is at d_lod, 1 when at d_{lod+1}.
 * Matches blueprint step 19.
 */
export function computeLodBlendAlpha(distance, d0, R, lod) {
  const lower = d0 * Math.pow(R, lod);
  const upper = d0 * Math.pow(R, lod + 1);
  if (upper <= lower) return 0;
  const t = Math.max(0, Math.min(1, (distance - lower) / (upper - lower)));
  return t * t * (3 - 2 * t); // smoothstep
}

/**
 * Computes the tile priority for a streaming queue.
 * Priority = α/d + β·|cosφ| + γ(1 − d_norm)
 * Matches blueprint step 26.
 *
 * @param {number} distance – distance from camera to tile center
 * @param {number} cosPhi – |cos(angle between tile direction and camera forward)|
 * @param {number} dNorm – normalized distance in [0, 1] (0 = at camera)
 * @param {number} alpha – distance weight (default 1.0)
 * @param {number} beta – direction weight (default 0.5)
 * @param {number} gamma – normalized-distance weight (default 0.3)
 */
export function computeTilePriority(distance, cosPhi, dNorm, alpha = 1.0, beta = 0.5, gamma = 0.3) {
  const invDist = 1 / Math.max(distance, 0.001);
  const absCos = Math.abs(cosPhi);
  const invNorm = 1 - Math.max(0, Math.min(1, dNorm));
  return alpha * invDist + beta * absCos + gamma * invNorm;
}

