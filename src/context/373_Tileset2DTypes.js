/**
 * Packs a tile coordinate (lod, x, y, z) into a single uint32 for use as a
 * hash key. Assumes each coordinate fits in 7 bits (0..127), giving 28 bits
 * total. For larger coordinates, callers should use the string variant.
 */
export function packTileKey(lod, x, y, z) {
  return ((lod & 0x7f) << 21) | ((x & 0x7f) << 14) | ((y & 0x7f) << 7) | (z & 0x7f);
}

/**
 * Produces a string key for a tile coordinate. Allocates; use only at
 * ingestion time, never in the render loop.
 */
export function stringTileKey(lod, x, y, z) {
  return `${lod}:${x}:${y}:${z}`;
}

/**
 * FNV-1a hash for arbitrary-length strings. Used to key source-level
 * registries by file path or logical name.
 */
export function fnv1aHash(str) {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = (h * 16777619) >>> 0;
  }
  return h;
}

