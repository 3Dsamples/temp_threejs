/**
 * Comparator for tile priority queues: higher priority first, ties broken
 * by insertion order (older first) to preserve FIFO fairness.
 * Callers build an array of { priority, seq } objects, not typed arrays,
 * so this is only called during ingestion, never in the render loop.
 */
export function compareTilePriority(a, b) {
  if (b.priority !== a.priority) return b.priority - a.priority;
  return a.seq - b.seq;
}

