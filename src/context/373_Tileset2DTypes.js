/**
 * Returns the four child coordinates of a tile in Morton order.
 * Children are ordered: 0=NW, 1=NE, 2=SW, 3=SE.
 * Writes into the caller-supplied Int32Array of length 4 (x,y pairs).
 */
export function computeChildTileCoords(lod, x, y, outChildCoords) {
  const childLod = lod + 1;
  const baseX = x * 2;
  const baseY = y * 2;
  // NW
  outChildCoords[0] = childLod; outChildCoords[1] = baseX;
  outChildCoords[2] = childLod; outChildCoords[3] = baseY;
  // NE
  outChildCoords[4] = childLod; outChildCoords[5] = baseX + 1;
  outChildCoords[6] = childLod; outChildCoords[7] = baseY;
  // SW
  outChildCoords[8]  = childLod; outChildCoords[9]  = baseX;
  outChildCoords[10] = childLod; outChildCoords[11] = baseY + 1;
  // SE
  outChildCoords[12] = childLod; outChildCoords[13] = baseX + 1;
  outChildCoords[14] = childLod; outChildCoords[15] = baseY + 1;
}

/**
 * Returns the parent tile coordinate for a given (lod, x, y).
 * Returns null if lod is 0 (root has no parent).
 */
export function computeParentTileCoord(lod, x, y) {
  if (lod <= 0) return null;
  return { lod: lod - 1, x: Math.floor(x / 2), y: Math.floor(y / 2) };
}

/**
 * Returns the four neighbor coordinates (N, E, S, W) of a tile at the same LOD.
 * Neighbors that fall outside the LOD grid are returned as null.
 */
export function computeTileNeighbors(lod, x, y, gridSize) {
  const neighbors = {
    north: y > 0 ? { lod, x, y: y - 1 } : null,
    east:  x < gridSize - 1 ? { lod, x: x + 1, y } : null,
    south: y < gridSize - 1 ? { lod, x, y: y + 1 } : null,
    west:  x > 0 ? { lod, x: x - 1, y } : null
  };
  return neighbors;
}

