/**
 * Creates a fresh SoA tile container sized for `capacity` tiles.
 * All fields are typed arrays; no per-tile JS objects, no GC pressure.
 * Callers resize by creating a new container and copying active ranges.
 */
export function createTileContainer(capacity) {
  return {
    capacity,
    count: 0,
    // Identity
    ids:             new Uint32Array(capacity),
    tilesetIds:      new Uint32Array(capacity),
    // Quadtree coordinates
    tileX:           new Int32Array(capacity),
    tileY:           new Int32Array(capacity),
    tileZ:           new Int32Array(capacity),
    lod:             new Uint8Array(capacity),
    // State & refinement
    state:           new Uint8Array(capacity),
    refinement:      new Uint8Array(capacity),
    contentFormat:   new Uint8Array(capacity),
    // Hierarchy
    parentId:        new Uint32Array(capacity),
    child0:          new Uint32Array(capacity),
    child1:          new Uint32Array(capacity),
    child2:          new Uint32Array(capacity),
    child3:          new Uint32Array(capacity),
    // Geometry pointers (ranges into shared arenas)
    vertexStart:     new Uint32Array(capacity),
    vertexCount:     new Uint32Array(capacity),
    indexStart:      new Uint32Array(capacity),
    indexCount:      new Uint32Array(capacity),
    // Bounding volume (SoA)
    boundsKind:      new Uint8Array(capacity),
    boundsX:         new Float64Array(capacity),
    boundsY:         new Float64Array(capacity),
    boundsZ:         new Float64Array(capacity),
    boundsW:         new Float64Array(capacity),
    boundsH:         new Float64Array(capacity),
    boundsD:         new Float64Array(capacity),
    boundsRadius:    new Float32Array(capacity),
    // Metrics
    geometricError:  new Float32Array(capacity),
    screenSpaceError:new Float32Array(capacity),
    blendAlpha:      new Float32Array(capacity),
    // Seam flags
    seamFlags:       new Uint8Array(capacity),
    // LRU
    lastUsedTick:    new Uint32Array(capacity),
    // Free-list bookkeeping
    freeIndices:     new Uint32Array(capacity),
    freeCount:       capacity,
    nextId:          1
  };
}

/**
 * Allocates an index in the container (swap-and-pop free-list).
 * Returns -1 if the container is full.
 */
export function tileContainerAlloc(container) {
  if (container.freeCount === 0) return -1;
  const idx = container.freeIndices[--container.freeCount];
  container.count++;
  return idx;
}

/**
 * Releases an index back to the container.
 * Callers must first remove any external references.
 */
export function tileContainerRelease(container, idx) {
  if (idx < 0 || idx >= container.capacity) return;
  container.freeIndices[container.freeCount++] = idx;
  container.count--;
}

/**
 * Resets all fields for a tile index (used after release and before reuse).
 */
export function tileContainerResetSlot(container, idx) {
  container.ids[idx] = 0;
  container.tilesetIds[idx] = 0;
  container.tileX[idx] = 0;
  container.tileY[idx] = 0;
  container.tileZ[idx] = 0;
  container.lod[idx] = 0;
  container.state[idx] = TileState.UNLOADED;
  container.refinement[idx] = TileRefinement.REPLACE;
  container.contentFormat[idx] = TilesetSourceFormat.UNKNOWN;
  container.parentId[idx] = 0xFFFFFFFF;
  container.child0[idx] = 0xFFFFFFFF;
  container.child1[idx] = 0xFFFFFFFF;
  container.child2[idx] = 0xFFFFFFFF;
  container.child3[idx] = 0xFFFFFFFF;
  container.vertexStart[idx] = 0;
  container.vertexCount[idx] = 0;
  container.indexStart[idx] = 0;
  container.indexCount[idx] = 0;
  container.boundsKind[idx] = BoundingVolumeKind.SPHERE;
  container.boundsX[idx] = 0;
  container.boundsY[idx] = 0;
  container.boundsZ[idx] = 0;
  container.boundsW[idx] = 0;
  container.boundsH[idx] = 0;
  container.boundsD[idx] = 0;
  container.boundsRadius[idx] = 0;
  container.geometricError[idx] = 0;
  container.screenSpaceError[idx] = 0;
  container.blendAlpha[idx] = 1;
  container.seamFlags[idx] = 0;
  container.lastUsedTick[idx] = 0;
}

