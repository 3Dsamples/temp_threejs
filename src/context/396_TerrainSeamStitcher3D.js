//### Description : Context-aware 3D seam stitcher for the seamless terrain
//###               pipeline. This is the module that guarantees crack-free
//###               transitions between adjacent 3D terrain tiles — the exact
//###               problem that quantized-mesh, I3S, procedural mesh, and
//###               heightmap families all share when rendered at different LOD
//###               levels. Implements the three complementary strategies that
//###               any production terrain renderer needs:
//###                 1. SKIRT-BASED STITCHING — extends the lower-LOD tile’s
//###                    edges downward with skirt quads (already generated by
//###                    files 389/393) so the higher-LOD neighbor’s crack is
//###                    covered without changing topology. The stitcher sizes
//###                    each skirt dynamically based on the maximum elevation
//###                    mismatch along the shared edge.
//###                 2. HALF-QUAD STITCHING — for adjacent tiles at the same
//###                    LOD but with different vertex densities, inserts
//###                    half-vertex triangles on the higher-density side to
//###                    match the coarser edge. Classic T-junction repair.
//###                 3. VERTEX WELDING — snaps coincident vertices on the
//###                    shared edge to a common position with a configurable
//###                    tolerance (default 1e-4 world units) so triangle seams
//###                    are mathematically identical. Eliminates z-fighting and
//###                    normal discontinuities.
//###               The stitcher runs per-tile at 10 Hz (metabolism tier). It
//###               reads the per-edge vertex lists published by each tile’s
//###               decoder (westIndices / southIndices / eastIndices /
//###               northIndices for quantized-mesh and I3S; grid edges for
//###               heightmap tiles; boundary vertices for procedural meshes),
//###               matches them against the neighbor’s edge, computes the
//###               optimal strategy for that edge, and writes the resulting
//###               stitch data into the physical channel where the 3D render
//###               dispatcher (file 393) consumes it directly. Every edge is
//###               processed at most once per (tileKey, edge) pair, and all
//###               stitch state is cached in a bounded LRU so a stationary
//###               camera does zero work per frame. All per-edge geometry is
//###               stored in a structure-of-arrays arena; no per-stitch
//###               allocation in the hot path. Emits seam events to the
//###               dispatcher for downstream audio/particle effects (e.g.
//###               wind whistling through a crack). Binds every stitched edge
//###               to an ECS entity with SeamStitch3DComponent.
//###               No external loader, no CDN access, no static server.
//###               Designed for Android arm64 under the 8 ms per-tick CPU
//###               ceiling and 200 MB resident memory cap, and scales from
//###               a single 10-unit tile to galactic streaming (10k+ units)
//###               without main-thread stalls.
//### Best for : Any 3D terrain pipeline where tiles at different LODs share
//###            edges — which is every 3D terrain pipeline. Without the
//###            stitcher, quantized-mesh tiles crack at LOD boundaries, I3S
//###            tiles show visible gaps, procedural meshes leak the skybox
//###            through the seams, and heightmap grids show flickering
//###            z-fighting. With the stitcher, all four families render
//###            seamlessly and can be mixed in the same view without any
//###            family-specific workarounds in the renderer.
//### License : MIT

