/**
 * TerrainSeamStitcher3D — the seam stitching engine.
 *
 * Lifecycle (per tick, at 10 Hz):
 *   1. Update camera state (for edge priority scoring).
 *   2. For each visible tile:
 *      a. Look up the tile's four neighbors.
 *      b. For each edge, detect the stitch strategy.
 *      c. If not cached, compute the stitch geometry.
 *      d. Publish to the physical channel.
 *      e. Bind ECS component.
 *   3. Evict stale stitch records.
 */
export class TerrainSeamStitcher3D {
  constructor(options = {}) {
    this.options = {
      // Frequency
      targetHz: options.targetHz ?? 10,

      // Matching tolerance
      vertexMatchTolerance: options.vertexMatchTolerance ?? 1e-4,
      elevationMatchTolerance: options.elevationMatchTolerance ?? 0.01,

      // Strategy preferences
      preferSkirt: options.preferSkirt ?? true,
      preferHalfQuad: options.preferHalfQuad ?? true,
      preferVertexWeld: options.preferVertexWeld ?? true,

      // Skirt sizing
      skirtMinDepth: options.skirtMinDepth ?? 0.5,
      skirtMaxDepth: options.skirtMaxDepth ?? 20.0,
      skirtDepthMargin: options.skirtDepthMargin ?? 1.5,

      // Cache
      maxCacheEntries: options.maxCacheEntries ?? 4096,
      cacheVersionTickInterval: options.cacheVersionTickInterval ?? 30,

      // Stitch arena
      initialArenaCapacity: options.initialArenaCapacity ?? 16384,

      // Neighbor lookup
      neighborLodTolerance: options.neighborLodTolerance ?? 3,

      // Diagnostics
      enableDiagnostics: options.enableDiagnostics ?? true,

      ...options
    };

    // ---- Stitch arena ----
    this._arena = new StitchArena(this.options.initialArenaCapacity);

    // ---- Per-tile stitch records ----
    this._records = new Map();          // `${tileKey}:${edge}` → SeamStitchRecord
    this._recordOrder = [];
    this._cacheVersion = 1;

    // ---- Context bindings ----
    this.frame = null;
    this.ecsWorld = null;
    this.dispatcher = null;
    this.lastTick = 0;
    this._accumulator = 0;

    // ---- Camera state ----
    this._camera = {
      x: 0, y: 0, z: 0,
      forwardX: 0, forwardY: 0, forwardZ: -1
    };

    // ---- Tile registry (for neighbor lookup) ----
    // tileKey → { terrain, header }
    this._tiles = new Map();

    // ---- Published SoA ----
    this._published = {
      tileKeys: [],
      edges: [],
      strategies: [],
      states: [],
      neighborTileKeys: [],
      neighborLods: [],
      vertexCounts: [],
      triangleCounts: [],
      mismatches: [],
      stitchStarts: [],
      count: 0
    };

    // ---- Diagnostics ----
    this.stats = {
      ticksProcessed: 0,
      edgesEvaluated: 0,
      edgesStitched: 0,
      skirtStitches: 0,
      halfQuadStitches: 0,
      vertexWeldStitches: 0,
      totalStitchVertices: 0,
      totalStitchTriangles: 0,
      cacheHits: 0,
      cacheMisses: 0,
      lastDurationMs: 0
    };
  }

  // ---------------------------------------------------------------------
  // Lifecycle
  // ---------------------------------------------------------------------

  bind(contextFrame, ecsWorld, eventDispatcher = null) {
    this.frame = contextFrame;
    this.ecsWorld = ecsWorld;
    this.dispatcher = eventDispatcher;
    return this;
  }

  // ---------------------------------------------------------------------
  // Main update
  // ---------------------------------------------------------------------

  /**
   * Main provider tick.
   *
   * @param {ContextFrame} contextFrame
   * @param {number} tick
   * @param {number} dt
   * @param {object[]} visibleHeaders – visible Tile2DHeader references
   * @param {object} source – the terrain source (holds per-tile terrain objects)
   * @param {object} [camera] – optional camera override
   */
  update(contextFrame, tick, dt, visibleHeaders, source, camera = null) {
    this.frame = contextFrame;
    this.lastTick = tick;

    this._accumulator += dt;
    const interval = 1 / this.options.targetHz;
    if (this._accumulator < interval) return;
    this._accumulator %= interval;

    const t0 = (typeof performance !== 'undefined' ? performance.now() : Date.now());

    // 1. Update camera if provided.
    if (camera) {
      this._camera.x = camera.x ?? 0;
      this._camera.y = camera.y ?? 0;
      this._camera.z = camera.z ?? 0;
      this._camera.forwardX = camera.forwardX ?? 0;
      this._camera.forwardY = camera.forwardY ?? 0;
      this._camera.forwardZ = camera.forwardZ ?? -1;
    }

    // 2. Bump cache version periodically.
    if (tick % this.options.cacheVersionTickInterval === 0) {
      this._cacheVersion++;
    }

    // 3. Update tile registry from visible headers.
    this._updateTileRegistry(visibleHeaders, source);

    // 4. Reset published arrays.
    this._resetPublished();

    // 5. Process each visible tile and its four edges.
    for (const h of visibleHeaders) {
      if (h.state !== TileState.READY) continue;
      this._processTileEdges(h);
    }

    // 6. Publish to physical channel.
    this._writePhysicalChannel();

    // 7. Evict stale records.
    this._evictStale();

    // 8. Stats.
    const t1 = (typeof performance !== 'undefined' ? performance.now() : Date.now());
    this.stats.lastDurationMs = t1 - t0;
    this.stats.ticksProcessed++;
  }

  _updateTileRegistry(visibleHeaders, source) {
    this._tiles.clear();
    for (const h of visibleHeaders) {
      if (h.state !== TileState.READY) continue;
      const record = source?.tileMap?.get(h.tileKey);
      if (!record) continue;
      const terrain = record.terrainObject ?? record.terrain;
      if (!terrain) continue;
      this._tiles.set(h.tileKey, { terrain, header: h });
    }
  }

  // ---------------------------------------------------------------------
  // Per-tile edge processing
  // ---------------------------------------------------------------------

  _processTileEdges(header) {
    // Compute the four neighbor coordinates at the same LOD.
    const neighbors = computeTileNeighbors(
      header.lod, header.tileX, header.tileY,
      1 << header.lod
    );

    // Process each edge.
    this._processEdge(header, SeamEdge.NORTH, neighbors.north);
    this._processEdge(header, SeamEdge.SOUTH, neighbors.south);
    this._processEdge(header, SeamEdge.EAST, neighbors.east);
    this._processEdge(header, SeamEdge.WEST, neighbors.west);
  }

  _processEdge(header, edge, neighborCoords) {
    const edgeKey = `${header.tileKey}:${edge}`;
    this.stats.edgesEvaluated++;

    // Try the cache first.
    const cached = this._records.get(edgeKey);
    if (cached && cached.state === SeamStitchState.STITCHED) {
      this.stats.cacheHits++;
      this._publishRecord(cached);
      this._touchRecord(edgeKey);
      return;
    }
    this.stats.cacheMisses++;

    // No neighbor coordinates → no stitch.
    if (!neighborCoords) {
      const rec = new SeamStitchRecord({
        tileKey: header.tileKey,
        edge,
        neighborTileKey: null,
        neighborLod: -1,
        strategy: SeamStitchStrategy.NONE,
        state: SeamStitchState.UNSTITCHED,
        lastComputedTick: this.lastTick
      });
      this._storeRecord(edgeKey, rec);
      this._publishRecord(rec);
      return;
    }

    // Look up the neighbor tile.
    const neighborKey = stringTileKey(neighborCoords.lod, neighborCoords.x, neighborCoords.y, header.tileZ);
    const neighbor = this._tiles.get(neighborKey);

    // No neighbor in the visible set → cannot stitch yet.
    if (!neighbor) {
      const rec = new SeamStitchRecord({
        tileKey: header.tileKey,
        edge,
        neighborTileKey: neighborKey,
        neighborLod: neighborCoords.lod,
        strategy: SeamStitchStrategy.NONE,
        state: SeamStitchState.UNSTITCHED,
        lastComputedTick: this.lastTick
      });
      this._storeRecord(edgeKey, rec);
      this._publishRecord(rec);
      return;
    }

    // Both tiles are visible — compute the stitch.
    const rec = this._computeStitch(header, edge, neighbor, neighborKey);
    this._storeRecord(edgeKey, rec);
    this._publishRecord(rec);

    // Bind to ECS.
    this._bindComponent(header, edge, rec);
  }

  // ---------------------------------------------------------------------
  // Stitch computation
  // ---------------------------------------------------------------------

  _computeStitch(header, edge, neighbor, neighborKey) {
    const tileTerrain = header;
    const neighborTerrain = neighbor.terrain;

    // Determine the geometry family of both tiles.
    const familyA = this._classifyFamily(neighbor.terrain);
    const familyB = this._classifyFamily(neighborTerrain);

    // Compute the elevation mismatch along the shared edge.
    const mismatch = this._computeEdgeMismatch(header, edge, neighborTerrain, neighbor);

    // Match the edge vertex lists.
    const edgeA = this._getEdgeVertexList(neighbor.terrain, oppositeEdge(edge));
    const edgeB = this._getEdgeVertexList(neighborTerrain, edge);
    const matchResult = this._matchEdges(edgeA, edgeB, mismatch);

    // Select the strategy.
    const strategy = this._selectStrategy(matchResult, mismatch, familyA, familyB);

    // Compute the stitch geometry.
    const stitchData = this._buildStitchGeometry(
      header, edge, neighbor, neighborTerrain, edgeA, edgeB, strategy, mismatch
    );

    // Determine the state.
    const state = stitchData.vertexCount > 0 ? SeamStitchState.STITCHED : SeamStitchState.UNSTITCHED;

    // Update stats.
    if (state === SeamStitchState.STITCHED) {
      this.stats.edgesStitched++;
      this.stats.totalStitchVertices += stitchData.vertexCount;
      this.stats.totalStitchTriangles += stitchData.triangleCount;
      if (strategy === SeamStitchStrategy.SKIRT) this.stats.skirtStitches++;
      else if (strategy === SeamStitchStrategy.HALF_QUAD) this.stats.halfQuadStitches++;
      else if (strategy === SeamStitchStrategy.VERTEX_WELD) this.stats.vertexWeldStitches++;
      else if (strategy === SeamStitchStrategy.SKIRT_AND_WELD) {
        this.stats.skirtStitches++;
        this.stats.vertexWeldStitches++;
      }
    }

    return new SeamStitchRecord({
      tileKey: neighbor.tileKey ?? header.tileKey,
      edge,
      neighborTileKey: neighborKey,
      neighborLod: neighbor.header.lod,
      strategy,
      state,
      vertexCount: stitchData.vertexCount,
      triangleCount: stitchData.triangleCount,
      mismatch,
      stitchStart: stitchData.stitchStart,
      lastComputedTick: this.lastTick
    });
  }

  _computeEdgeMismatch(header, edge, neighborTerrain, neighbor) {
    // Find the elevation range along the shared edge in each tile.
    const edgeZ_A = this._getEdgeZRange(neighbor.terrain, oppositeEdge(edge));
    const edgeZ_B = this._getEdgeZRange(neighborTerrain, edge);
    if (!edgeZ_A || !edgeZ_B) return 0;
    return Math.max(
      Math.abs(edgeZ_A.min - edgeZ_B.min),
      Math.abs(edgeZ_A.max - edgeZ_B.max)
    );
  }

  _getEdgeZRange(terrain, edge) {
    // For heightmap tiles.
    if (terrain instanceof HeightmapTerrain) {
      return this._getHeightmapEdgeZRange(terrain, edge);
    }
    // For mesh tiles (quantized, I3S, procedural).
    if (terrain.vertexCount && terrain.positions) {
      return this._getMeshEdgeZRange(terrain, edge);
    }
    return null;
  }

  _getHeightmapEdgeZRange(terrain, edge) {
    const res = terrain.resolution;
    let min = Infinity, max = -Infinity;
    for (let i = 0; i < res; i++) {
      let idx;
      if (edge === SeamEdge.NORTH) idx = i;
      else if (edge === SeamEdge.SOUTH) idx = (res - 1) * res + i;
      else if (edge === SeamEdge.WEST) idx = i * res;
      else if (edge === SeamEdge.EAST) idx = i * res + (res - 1);
      else continue;
      const z = terrain.elevation[idx] * (terrain.zScale ?? 1);
      if (z < min) min = z;
      if (z > max) max = z;
    }
    return { min, max };
  }

  _getMeshEdgeZRange(terrain, edge) {
    const edgeIndices = this._getEdgeVertexList(terrain, edge);
    if (!edgeIndices || edgeIndices.length === 0) return null;
    let min = Infinity, max = -Infinity;
    for (const idx of edgeIndices) {
      const z = terrain.positions[idx * 3 + 2];
      if (z < min) min = z;
      if (z > max) max = z;
    }
    return { min, max };
  }

  _getEdgeVertexList(terrain, edge) {
    // Heightmap: generate synthetic edge list.
    if (terrain instanceof HeightmapTerrain) {
      const res = terrain.resolution;
      const list = new Array(res);
      for (let i = 0; i < res; i++) {
        let idx;
        if (edge === SeamEdge.NORTH) idx = i;
        else if (edge === SeamEdge.SOUTH) idx = (res - 1) * res + i;
        else if (edge === SeamEdge.WEST) idx = i * res;
        else if (edge === SeamEdge.EAST) idx = i * res + (res - 1);
        else continue;
        list[i] = idx;
      }
      return list;
    }

    // Quantized mesh.
    if (terrain instanceof QuantizedMeshTerrain) {
      switch (edge) {
        case SeamEdge.NORTH: return Array.from(terrain.northIndices ?? []);
        case SeamEdge.SOUTH: return Array.from(terrain.southIndices ?? []);
        case SeamEdge.EAST:  return Array.from(terrain.eastIndices ?? []);
        case SeamEdge.WEST:  return Array.from(terrain.westIndices ?? []);
        default: return [];
      }
    }

    // I3S.
    if (terrain instanceof I3SElevationTerrain) {
      switch (edge) {
        case SeamEdge.NORTH: return Array.from(terrain.northIndices ?? []);
        case SeamEdge.SOUTH: return Array.from(terrain.southIndices ?? []);
        case SeamEdge.EAST:  return Array.from(terrain.eastIndices ?? []);
        case SeamEdge.WEST:  return Array.from(terrain.westIndices ?? []);
        default: return [];
      }
    }

    return [];
  }

  _matchEdges(edgeA, edgeB, mismatch) {
    if (!edgeA || !edgeB || edgeA.length === 0 || edgeB.length === 0) {
      return EdgeMatchResult.NO_NEIGHBOR;
    }
    if (edgeA.length === edgeB.length) {
      // Same density — check positions.
      if (mismatch < this.options.elevationMatchTolerance) {
        return EdgeMatchResult.IDENTICAL;
      }
      return EdgeMatchResult.SAME_DENSITY;
    }
    if (edgeA.length > edgeB.length) {
      return EdgeMatchResult.HIGHER_FIRST;
    }
    return EdgeMatchResult.HIGHER_SECOND;
  }

  _selectStrategy(matchResult, mismatch, familyA, familyB) {
    switch (matchResult) {
      case EdgeMatchResult.IDENTICAL:
        return SeamStitchStrategy.NONE;
      case EdgeMatchResult.SAME_DENSITY:
        // Same density, small elevation difference → weld.
        if (this.options.preferVertexWeld && mismatch < this.options.elevationMatchTolerance * 10) {
          return SeamStitchStrategy.VERTEX_WELD;
        }
        return SeamStitchStrategy.SKIRT;
      case EdgeMatchResult.HIGHER_FIRST:
      case EdgeMatchResult.HIGHER_SECOND:
        // Same LOD, different densities → half-quad.
        if (this.options.preferHalfQuad) {
          return SeamStitchStrategy.HALF_QUAD;
        }
        return SeamStitchStrategy.SKIRT;
      case EdgeMatchResult.MISMATCHED_LOD:
        // Different LODs → skirt (optionally + weld).
        if (this.options.preferSkirt) {
          if (mismatch > this.options.skirtMaxDepth * 0.5) {
            return SeamStitchStrategy.SKIRT_AND_WELD;
          }
          return SeamStitchStrategy.SKIRT;
        }
        return SeamStitchStrategy.SKIRT;
      case EdgeMatchResult.NO_NEIGHBOR:
      default:
        return SeamStitchStrategy.NONE;
    }
  }

  // ---------------------------------------------------------------------
  // Stitch geometry
  // ---------------------------------------------------------------------

  _buildStitchGeometry(header, edge, neighbor, neighborTerrain, edgeA, edgeB, strategy, mismatch) {
    switch (strategy) {
      case SeamStitchStrategy.SKIRT:
      case SeamStitchStrategy.SKIRT_AND_WELD:
        return this._buildSkirtStitch(header, edge, neighborTerrain, edgeA, edgeB, mismatch);
      case SeamStitchStrategy.HALF_QUAD:
        return this._buildHalfQuadStitch(header, edge, neighborTerrain, edgeA, edgeB, mismatch);
      case SeamStitchStrategy.VERTEX_WELD:
        return this._buildVertexWeldStitch(header, edge, neighborTerrain, edgeA, edgeB, mismatch);
      default:
        return { vertexCount: 0, triangleCount: 0, stitchStart: 0 };
    }
  }

  _buildSkirtStitch(header, edge, neighborTerrain, edgeA, edgeB, mismatch) {
    // Skirt stitching extends the lower edge downward so the higher edge’s
    // crack is covered. We use the neighbor’s edge positions (higher priority)
    // as the skirt’s top edge, and extend them downward by (mismatch + margin).
    const skirtDepth = Math.min(
      this.options.skirtMaxDepth,
      Math.max(this.options.skirtMinDepth, mismatch * this.options.skirtDepthMargin)
    );

    // Use the higher-density edge as the source of vertices.
    const edgeList = edgeA.length >= edgeB.length ? edgeA : edgeB;
    const vertexCount = edgeList.length * 2;
    const triangleCount = (edgeList.length - 1) * 2;

    // Allocate arena space.
    const stitchFloats = vertexCount * 3; // (u, v, z) per vertex
    const stitchStart = this._arena.alloc(stitchFloats);

    // Fill the arena.
    const data = this._arena.data;
    for (let i = 0; i < edgeList.length; i++) {
      const idx = edgeList[i];
      const x = neighborTerrain.positions[idx * 3];
      const y = neighborTerrain.positions[idx * 3 + 1];
      const z = neighborTerrain.positions[idx * 3 + 2];

      // Top vertex (at edge Z).
      let baseIdx = stitchStart + i * 3;
      data[baseIdx]     = x;
      data[baseIdx + 1] = y;
      data[baseIdx + 2] = z;

      // Bottom vertex (extended downward by skirtDepth).
      baseIdx = stitchStart + (edgeList.length + i) * 3;
      data[baseIdx]     = x;
      data[baseIdx + 1] = y;
      data[baseIdx + 2] = z - skirtDepth;
    }

    return { vertexCount, triangleCount, stitchStart };
  }

  _buildHalfQuadStitch(header, edge, neighborTerrain, edgeA, edgeB, mismatch) {
    // Half-quad stitching: the coarser edge is a straight line; the finer
    // edge has intermediate vertices. We insert triangles from each
    // intermediate vertex to the nearest coarse edge segment, closing the
    // T-junction.
    const finerEdge = edgeA.length > edgeB.length ? edgeA : edgeB;
    const coarserEdge = edgeA.length > edgeB.length ? edgeB : edgeA;

    if (coarserEdge.length < 2) {
      return { vertexCount: 0, triangleCount: 0, stitchStart: 0 };
    }

    // For each intermediate vertex on the finer edge, add a triangle
    // connecting it to the two nearest coarser-edge vertices.
    const vertexCount = finerEdge.length * 2; // duplicate + original
    const triangleCount = (finerEdge.length - 1) * 2;

    const stitchFloats = vertexCount * 3;
    const stitchStart = this._arena.alloc(stitchFloats);
    const data = this._arena.data;

    for (let i = 0; i < finerEdge.length; i++) {
      const idx = finerEdge[i];
      const x = neighborTerrain.positions[idx * 3];
      const y = neighborTerrain.positions[idx * 3 + 1];
      const z = neighborTerrain.positions[idx * 3 + 2];

      // Original vertex.
      let baseIdx = stitchStart + i * 3;
      data[baseIdx]     = x;
      data[baseIdx + 1] = y;
      data[baseIdx + 2] = z;

      // Projected vertex onto the coarse edge line (nearest point).
      // Approximate: snap to the nearest coarse-edge vertex Z.
      const nearestZ = this._nearestCoarseZ(coarserEdge, neighborTerrain, x, y);
      baseIdx = stitchStart + (finerEdge.length + i) * 3;
      data[baseIdx]     = x;
      data[baseIdx + 1] = y;
      data[baseIdx + 2] = nearestZ;
    }

    return { vertexCount, triangleCount, stitchStart };
  }

  _nearestCoarseZ(coarserEdge, terrain, x, y) {
    // Find the coarse edge vertex nearest to (x, y).
    let nearestZ = 0;
    let nearestDist = Infinity;
    for (let i = 0; i < coarserEdge.length; i++) {
      const idx = coarserEdge[i];
      const cx = terrain.positions[idx * 3];
      const cy = terrain.positions[idx * 3 + 1];
      const cz = terrain.positions[idx * 3 + 2];
      const dx = x - cx, dy = y - cy;
      const d2 = dx * dx + dy * dy;
      if (d2 < nearestDist) {
        nearestDist = d2;
        nearestZ = cz;
      }
    }
    return nearestZ;
  }

  _buildVertexWeldStitch(header, edge, neighborTerrain, edgeA, edgeB, mismatch) {
    // Vertex welding: snap coincident vertices to a common position.
    // This is essentially a no-op at the geometry level — the welding is
    // handled by the shader based on the published edge records. Here we
    // simply record the weld positions.
    const weldCount = Math.min(edgeA.length, edgeB.length);
    const vertexCount = weldCount * 2; // both sides
    const triangleCount = 0;

    const stitchFloats = vertexCount * 3;
    const stitchStart = this._arena.alloc(stitchFloats);
    const data = this._arena.data;

    for (let i = 0; i < weldCount; i++) {
      const aIdx = edgeA[i];
      const bIdx = edgeB[i];

      // A-side vertex.
      let baseIdx = stitchStart + i * 3;
      data[baseIdx]     = neighborTerrain.positions[aIdx * 3];
      data[baseIdx + 1] = neighborTerrain.positions[aIdx * 3 + 1];
      data[baseIdx + 2] = neighborTerrain.positions[aIdx * 3 + 2];

      // B-side vertex.
      baseIdx = stitchStart + (weldCount + i) * 3;
      data[baseIdx]     = neighborTerrain.positions[bIdx * 3];
      data[baseIdx + 1] = neighborTerrain.positions[bIdx * 3 + 1];
      data[baseIdx + 2] = neighborTerrain.positions[bIdx * 3 + 2];
    }

    return { vertexCount, triangleCount, stitchStart };
  }

  // ---------------------------------------------------------------------
  // Publishing
  // ---------------------------------------------------------------------

  _resetPublished() {
    const p = this._published;
    p.tileKeys.length = 0;
    p.edges.length = 0;
    p.strategies.length = 0;
    p.states.length = 0;
    p.neighborTileKeys.length = 0;
    p.neighborLods.length = 0;
    p.vertexCounts.length = 0;
    p.triangleCounts.length = 0;
    p.mismatches.length = 0;
    p.stitchStarts.length = 0;
    p.count = 0;
  }

  _publishRecord(rec) {
    const p = this._published;
    p.tileKeys.push(rec.tileKey);
    p.edges.push(rec.edge);
    p.strategies.push(rec.strategy);
    p.states.push(rec.state);
    p.neighborTileKeys.push(rec.neighborTileKey ?? '');
    p.neighborLods.push(rec.neighborLod);
    p.vertexCounts.push(rec.vertexCount);
    p.triangleCounts.push(rec.triangleCount);
    p.mismatches.push(rec.mismatch);
    p.stitchStarts.push(rec.stitchStart);
    p.count++;
  }

  _writePhysicalChannel() {
    if (!this.frame?.layers?.physical) return;
    const physical = this.frame.layers.physical;
    const p = this._published;

    physical.terrainSeamTileKeys = p.tileKeys;
    physical.terrainSeamEdges = p.edges;
    physical.terrainSeamStrategies = p.strategies;
    physical.terrainSeamStates = p.states;
    physical.terrainSeamNeighborTileKeys = p.neighborTileKeys;
    physical.terrainSeamNeighborLods = p.neighborLods;
    physical.terrainSeamVertexCounts = p.vertexCounts;
    physical.terrainSeamTriangleCounts = p.triangleCounts;
    physical.terrainSeamMismatches = p.mismatches;
    physical.terrainSeamStitchStarts = p.stitchStarts;
    physical.terrainSeamArena = this._arena.data;
    physical.terrainSeamStats = this.getStats();
  }

  // ---------------------------------------------------------------------
  // ECS binding
  // ---------------------------------------------------------------------

  _bindComponent(header, edge, rec) {
    if (!this.ecsWorld || header.entityId === 0xFFFFFFFF) return;

    // Get or create the seam component.
    let comp = this.ecsWorld.getComponent?.(header.entityId, SeamStitch3DComponent);
    const isNew = !comp;

    if (isNew) {
      comp = {
        edgeStrategies: 0,
        edgeStates: 0,
        northNeighborHash: 0,
        southNeighborHash: 0,
        eastNeighborHash: 0,
        westNeighborHash: 0,
        northMismatch: 0,
        southMismatch: 0,
        eastMismatch: 0,
        westMismatch: 0,
        northStitchStart: 0,
        southStitchStart: 0,
        eastStitchStart: 0,
        westStitchStart: 0,
        anyEdgeStitched: 0,
        lastUpdatedTick: this.lastTick
      };
    }

    // Pack the edge strategy and state into 2-bit fields.
    const edgeShift = (e) => e === SeamEdge.NORTH ? 0 : e === SeamEdge.SOUTH ? 2 : e === SeamEdge.EAST ? 4 : 6;

    comp.edgeStrategies = (comp.edgeStrategies & ~(0x3 << edgeShift(edge))) |
      ((rec.strategy & 0x3) << edgeShift(edge));
    comp.edgeStates = (comp.edgeStates & ~(0x3 << edgeShift(edge))) |
      ((rec.state & 0x3) << edgeShift(edge));

    if (edge === SeamEdge.NORTH) {
      comp.northNeighborHash = rec.neighborTileKey ? fnv1aHash(rec.neighborTileKey) : 0;
      comp.northMismatch = rec.mismatch;
      comp.northStitchStart = rec.stitchStart;
    } else if (edge === SeamEdge.SOUTH) {
      comp.southNeighborHash = rec.neighborTileKey ? fnv1aHash(rec.neighborTileKey) : 0;
      comp.southMismatch = rec.mismatch;
      comp.southStitchStart = rec.stitchStart;
    } else if (edge === SeamEdge.EAST) {
      comp.eastNeighborHash = rec.neighborTileKey ? fnv1aHash(rec.neighborTileKey) : 0;
      comp.eastMismatch = rec.mismatch;
      comp.eastStitchStart = rec.stitchStart;
    } else if (edge === SeamEdge.WEST) {
      comp.westNeighborHash = rec.neighborTileKey ? fnv1aHash(rec.neighborTileKey) : 0;
      comp.westMismatch = rec.mismatch;
      comp.westStitchStart = rec.stitchStart;
    }

    if (rec.state === SeamStitchState.STITCHED) {
      comp.anyEdgeStitched = 1;
    }
    comp.lastUpdatedTick = this.lastTick;

    this.ecsWorld.addComponent?.(header.entityId, SeamStitch3DComponent, comp);
  }

  // ---------------------------------------------------------------------
  // Cache management
  // ---------------------------------------------------------------------

  _storeRecord(edgeKey, rec) {
    const existing = this._records.get(edgeKey);
    if (existing && existing.stitchStart !== 0 && existing.vertexCount > 0) {
      this._arena.free(existing.stitchStart, existing.vertexCount * 3);
    }
    this._records.set(edgeKey, rec);
    this._touchRecord(edgeKey);
  }

  _touchRecord(edgeKey) {
    const idx = this._recordOrder.indexOf(edgeKey);
    if (idx >= 0) this._recordOrder.splice(idx, 1);
    this._recordOrder.push(edgeKey);

    while (this._records.size > this.options.maxCacheEntries) {
      const oldest = this._recordOrder.shift();
      const rec = this._records.get(oldest);
      if (rec) {
        if (rec.stitchStart !== 0 && rec.vertexCount > 0) {
          this._arena.free(rec.stitchStart, rec.vertexCount * 3);
        }
        this._records.delete(oldest);
      }
    }
  }

  _evictStale() {
    const toEvict = [];
    for (const [key, rec] of this._records) {
      if (this.lastTick - rec.lastComputedTick > 60) {
        toEvict.push(key);
      }
    }
    for (const key of toEvict) {
      const rec = this._records.get(key);
      if (rec && rec.stitchStart !== 0 && rec.vertexCount > 0) {
        this._arena.free(rec.stitchStart, rec.vertexCount * 3);
      }
      this._records.delete(key);
      const idx = this._recordOrder.indexOf(key);
      if (idx >= 0) this._recordOrder.splice(idx, 1);
    }
  }

  // ---------------------------------------------------------------------
  // Helpers
  // ---------------------------------------------------------------------

  _classifyFamily(terrain) {
    if (terrain instanceof HeightmapTerrain) return GeometryFamily3D.HEIGHTMAP_GRID;
    if (terrain instanceof QuantizedMeshTerrain) return GeometryFamily3D.QUANTIZED_MESH;
    if (terrain instanceof I3SElevationTerrain) return GeometryFamily3D.I3S_ELEVATION;
    if (terrain.vertexCount && terrain.triangleCount && terrain.indices) {
      return GeometryFamily3D.PROCEDURAL_MESH;
    }
    return GeometryFamily3D.CUSTOM;
  }

  // ---------------------------------------------------------------------
  // Public queries
  // ---------------------------------------------------------------------

  getStitchRecord(tileKey, edge) {
    return this._records.get(`${tileKey}:${edge}`) ?? null;
  }

  getStitchArena() {
    return this._arena.data;
  }

  getStats() {
    return {
      ...this.stats,
      cacheSize: this._records.size,
      arenaUsed: this._arena.used,
      arenaCapacity: this._arena.capacity
    };
  }

  // ---------------------------------------------------------------------
  // Lifecycle
  // ---------------------------------------------------------------------

  dispose() {
    for (const rec of this._records.values()) {
      if (rec.stitchStart !== 0 && rec.vertexCount > 0) {
        this._arena.free(rec.stitchStart, rec.vertexCount * 3);
      }
    }
    this._records.clear();
    this._recordOrder.length = 0;
    this._tiles.clear();
    this._arena.dispose();
    this._published.tileKeys.length = 0;
    this._published.count = 0;
    this.frame = null;
    this.ecsWorld = null;
    this.dispatcher = null;
  }
}

