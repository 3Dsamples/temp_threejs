/**
 * SeamStitchStrategy — the strategy selected for a given edge.
 *
 *   NONE              – no stitching needed (identical edges, or no neighbor)
 *   SKIRT             – extend with skirt quads (recommended for LOD mismatches)
 *   HALF_QUAD         – insert half-vertex triangles (same LOD, different density)
 *   VERTEX_WELD       – snap coincident vertices (same LOD, same density)
 *   SKIRT_AND_WELD    – skirt + vertex welding (worst-case LOD mismatch)
 */
export const SeamStitchStrategy = Object.freeze({
  NONE:            0,
  SKIRT:           1,
  HALF_QUAD:       2,
  VERTEX_WELD:     3,
  SKIRT_AND_WELD:  4
});

/**
 * SeamStitchState — the lifecycle state of a stitched edge.
 */
export const SeamStitchState = Object.freeze({
  UNSTITCHED:   0,
  STITCHING:    1,
  STITCHED:     2,
  STALE:        3
});

/**
 * EdgeMatchResult — the result of matching two edge vertex lists.
 */
export const EdgeMatchResult = Object.freeze({
  IDENTICAL:        0,   // same vertex count, same positions (within tolerance)
  SAME_DENSITY:     1,   // same vertex count, different positions
  HIGHER_FIRST:     2,   // first edge has more vertices
  HIGHER_SECOND:    3,   // second edge has more vertices
  MISMATCHED_LOD:   4,   // different LOD levels, cannot match vertex-to-vertex
  NO_NEIGHBOR:      5    // no adjacent tile
});

